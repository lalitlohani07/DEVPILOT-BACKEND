package com.lalit.devpilot.repository;

import java.util.List;
import java.util.Optional;

import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.transaction.annotation.Transactional;

import com.lalit.devpilot.model.Incident;

// Inherited, so no longer written by us:
//   save(Incident)  -> INSERT when id == 0, UPDATE otherwise
//   existsById(...)
public interface IncidentRepository extends JpaRepository<Incident, Integer> {

    // Overrides the inherited findById so the users are loaded in the same query.
    // Without "join fetch", reportedBy/assignedTo would be lazy proxies that fail
    // as soon as they're used outside a database session.
    @Override
    @Query("""
            select i from Incident i
            join fetch i.reportedBy
            left join fetch i.assignedTo
            where i.id = :id
            """)
    Optional<Incident> findById(@Param("id") Integer id);

    // One query instead of 1 + 2N. This is the fix for the old N+1 TODO.
    @Override
    @Query("""
            select i from Incident i
            join fetch i.reportedBy
            left join fetch i.assignedTo
            """)
    List<Incident> findAll();

    // A single DELETE statement. The database's ON DELETE CASCADE removes the
    // incident's events, exactly as it did with the JDBC version.
    @Modifying(clearAutomatically = true)
    @Transactional
    @Query("delete from Incident i where i.id = :id")
    int deleteIncidentById(@Param("id") int id);

    // Same signature as the JDBC version: true if a row was actually deleted.
    @Transactional
    default boolean delete(int id) {
        return deleteIncidentById(id) > 0;
    }

    // Same signature as the JDBC version: false if the incident doesn't exist.
    @Transactional
    default boolean update(Incident incident) {
        if (!existsById(incident.getId())) {
            return false;
        }
        save(incident);
        return true;
    }
}
